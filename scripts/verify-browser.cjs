const { chromium } = require('C:/Users/Ahmed Asif/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const fs = require('node:fs/promises');
const assert = require('node:assert/strict');
const base = 'http://127.0.0.1:3000';
const results = [];
let browser;
(async () => {
  await fs.mkdir('verification', { recursive: true });
  browser = await chromium.launch({ channel: 'msedge', headless: true, args: ['--disable-gpu'] });
  const errors = [];
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  const page = await context.newPage();
  page.on('pageerror', error => errors.push(error.message));
  const response = await page.goto(base, { waitUntil: 'networkidle', timeout: 60000 });
  assert.equal(response.status(), 200);
  await page.waitForTimeout(1200);
  await page.screenshot({ path: 'verification/desktop-hero.png' });
  for (const size of [[1440,1000],[1024,900],[768,1024],[390,844],[320,720]]) {
    await page.setViewportSize({ width: size[0], height: size[1] });
    await page.waitForTimeout(300);
    const overflow = await page.evaluate(() => ({ scroll: document.documentElement.scrollWidth, viewport: innerWidth, heading: document.querySelector('h1').getBoundingClientRect().toJSON() }));
    assert.ok(overflow.scroll <= overflow.viewport, `Horizontal overflow at ${size[0]}px: ${overflow.scroll}`);
    assert.ok(overflow.heading.right <= size[0], 'Hero title overflows');
    results.push({ width: size[0], horizontalOverflow: false });
    if (size[0] === 390) await page.screenshot({ path: 'verification/mobile-hero.png' });
  }
  await page.setViewportSize({ width:390, height:844 });
  const menu = page.locator('.menu-toggle');
  await menu.click(); assert.equal(await menu.getAttribute('aria-expanded'), 'true');
  await page.keyboard.press('Escape'); assert.equal(await menu.getAttribute('aria-expanded'), 'false');
  await menu.click(); await page.locator('#main-navigation').getByRole('link', {name:'Services', exact:true}).click();
  assert.equal(await menu.getAttribute('aria-expanded'), 'false');
  await page.locator('.service-details').first().locator('summary').click();
  assert.ok(await page.locator('.service-details').first().getAttribute('open') !== null);
  assert.equal(await page.locator('.service-details').first().locator('li').count(), 4);
  await page.locator('.service-details').first().locator('summary').click();
  const projectLinks = await page.locator('.project-card').evaluateAll(cards => cards.map(card => ({ url:card.href, target:card.target, rel:card.rel })));
  assert.equal(projectLinks.length,5);
  assert.ok(projectLinks.every(link => link.url.startsWith('https://') && link.target === '_blank' && link.rel.includes('noopener')));
  await page.locator('#contact').scrollIntoViewIfNeeded(); await page.waitForTimeout(700);
  await page.getByRole('button',{name:'Start a Conversation',exact:true}).click();
  assert.equal(await page.locator('[aria-invalid="true"]').count(),4);
  assert.equal(await page.locator('#contact-name').evaluate(input => input === document.activeElement),true);
  await page.locator('#contact-name').fill('Test Person');
  await page.locator('#contact-email').fill('person@example.com');
  await page.locator('#contact-service').selectOption('Website');
  await page.locator('#contact-details').fill('We would like a responsive website for our business.');
  await page.getByRole('button',{name:'Start a Conversation',exact:true}).click();
  await page.locator('.form-status.error').waitFor();
  assert.match(await page.locator('.form-status').innerText(), /not accepting messages yet/);
  assert.equal(await page.locator('#contact-name').inputValue(),'Test Person');
  await page.screenshot({path:'verification/mobile-contact.png'});
  await page.route('**/api/contact', route => route.fulfill({status:200,contentType:'application/json',body:JSON.stringify({success:true})}));
  await page.getByRole('button',{name:'Start a Conversation',exact:true}).click();
  await page.locator('.form-status.success').waitFor();
  assert.equal(await page.locator('#contact-name').inputValue(),'');
  await page.unroute('**/api/contact');
  await page.reload({waitUntil:'networkidle'});
  await page.setViewportSize({width:1440,height:1000});
  for (const [id,name] of [['work','desktop-work'],['services','desktop-services'],['contact','desktop-contact']]) {
    await page.locator(`#${id}`).evaluate(element => element.scrollIntoView({block:'start',behavior:'instant'})); await page.waitForTimeout(1000); await page.screenshot({path:`verification/${name}.png`});
  }
  await page.evaluate(() => window.scrollTo({top:0,behavior:'instant'})); await page.waitForTimeout(1200);
  assert.equal(await page.locator('h1').isVisible(),true);
  assert.ok(Number(await page.locator('h1').evaluate(element => getComputedStyle(element).opacity)) === 1);
  await page.locator('#work').scrollIntoViewIfNeeded(); await page.waitForTimeout(700);
  assert.equal(await page.locator('.project-preview img').count(),5);
  assert.ok(await page.locator('.project-preview img').evaluateAll(images => images.every(image => image.complete && image.naturalWidth>0)));
  // Force a genuinely broken image so browser cache cannot mask fallback behavior.
  await page.locator('.project-preview img').first().evaluate(image => { image.removeAttribute('srcset'); image.src='/missing-project-preview.webp'; });
  await page.locator('.project-fallback').first().waitFor();
  results.push({projectLinks:5,allImagesLoaded:true,brokenImageFallback:true,mobileMenu:true,serviceAccordion:true,formValidation:true,realUnconfiguredFormError:true,mockedFormSuccess:true,scrollDownAndUp:true,runtimeErrors:errors});
  assert.deepEqual(errors,[]);
  const reduced = await browser.newContext({viewport:{width:1440,height:1000},reducedMotion:'reduce'});
  const reducedPage = await reduced.newPage(); await reducedPage.goto(base,{waitUntil:'networkidle'});
  assert.equal(await reducedPage.evaluate(()=>matchMedia('(prefers-reduced-motion: reduce)').matches),true);
  assert.equal(await reducedPage.locator('h1').evaluate(element=>getComputedStyle(element).opacity),'1');
  await reducedPage.locator('#contact').scrollIntoViewIfNeeded();
  assert.equal(await reducedPage.locator('.contact-intro').evaluate(element=>getComputedStyle(element).opacity),'1');
  const noJS = await browser.newContext({javaScriptEnabled:false,viewport:{width:1440,height:1000}});
  const noJSPage = await noJS.newPage(); await noJSPage.goto(base,{waitUntil:'networkidle'});
  assert.equal(await noJSPage.locator('h1').innerText(),'Goodwork.');
  assert.equal(await noJSPage.locator('h1').evaluate(element=>getComputedStyle(element).opacity),'1');
  results.push({reducedMotion:true,serverRenderedContentWithoutJS:true});
  const origin=await context.request.post(`${base}/api/contact`,{data:{},headers:{origin:'https://untrusted.example'}});
  assert.equal(origin.status(),403);
  const invalid=await context.request.post(`${base}/api/contact`,{data:{email:'bad'},headers:{origin:base}});
  assert.equal(invalid.status(),400);
  const icon=await context.request.get(`${base}/icon.svg`);assert.equal(icon.status(),200);
  const og=await context.request.get(`${base}/opengraph-image`);assert.equal(og.status(),200);
  results.push({contactOriginGuard:true,serverValidation:true,favicon:true,openGraph:true});
  await fs.writeFile('verification/results.json',JSON.stringify(results,null,2));
  console.log(JSON.stringify(results,null,2));
})().catch(error => { console.error(error); process.exitCode = 1; }).finally(async () => { if (browser) await browser.close(); });
